import confetti from 'canvas-confetti';

export function fireWorkoutConfetti() {
  const end = Date.now() + 800;
  const colors = ['#c6ff00', '#ffffff', '#9ecc00'];

  (function frame() {
    confetti({
      particleCount: 3,
      angle: 60,
      spread: 55,
      origin: { x: 0, y: 0.7 },
      colors,
    });
    confetti({
      particleCount: 3,
      angle: 120,
      spread: 55,
      origin: { x: 1, y: 0.7 },
      colors,
    });
    if (Date.now() < end) requestAnimationFrame(frame);
  })();
}
